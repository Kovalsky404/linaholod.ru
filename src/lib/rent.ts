/**
 * Текст брони для Telegram. Ссылка на пост — чтобы менеджер узнал вещь
 * сразу, даже если названия похожи. Пустые строки «Дата / Время» — то, что
 * по правилам проката нужно указать при брони: человек дописывает их сам,
 * и менеджеру не приходится переспрашивать.
 */
export function rentalRequest(title: string, postUrl?: string): string {
  return [
    `Здравствуйте! Хочу забронировать «${title}» из каталога аренды.`,
    ...(postUrl ? [postUrl] : []),
    "Дата аренды: ",
    "Время получения и возврата: ",
  ].join("\n");
}

/** «1 вещь», «3 вещи», «12 вещей». */
export function itemsCount(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  const word =
    mod10 === 1 && mod100 !== 11
      ? "вещь"
      : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
        ? "вещи"
        : "вещей";
  return `${n} ${word}`;
}

/** Абзацы по пустой строке. */
export function toParagraphs(text: string): string[] {
  return text
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean);
}

/** Пункты по строкам; маркеры «•», «-», «—» в начале строки снимаются. */
export function toLines(text: string): string[] {
  return text
    .split(/\n+/)
    .map((t) => t.replace(/^\s*[•\-—–]\s*/, "").trim())
    .filter(Boolean);
}
